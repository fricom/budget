function colName(ci) { return ci < 26 ? String.fromCharCode(65 + ci) : String.fromCharCode(64 + Math.floor(ci / 26)) + String.fromCharCode(65 + ci % 26); }

async function main() {
  const auth = new google.auth.GoogleAuth({ keyFile: KEY_FILE, scopes: ['https://www.googleapis.com/auth/spreadsheets'] });
  const sheets = google.sheets({ version: 'v4', auth });
  const res = await sheets.spreadsheets.values.get({ spreadsheetId: SPREADSHEET_ID, range: '2026 소비내역!D4:BV103' });
  const rows = res.data.values || [];

  const blanks = [];
  MONTHS.forEach((mname, mi) => {
    const off = mi * 6;
    rows.forEach((row, ri) => {
      const cat = (row[off + 1] || '').trim();
      const item = (row[off + 2] || '').trim();
      const amt = row[off + 3] || '';
      if (item && !cat && amt !== '') blanks.push({ mi, ri, item, row: ri + 4, mname });
    });
  });

  const resolved = [];
  const stillUnresolved = {};
  blanks.forEach(b => {
    let cat = DICT[b.item];
    if (!cat && HYGIENE.some(h => b.item.includes(h)) && b.item.startsWith('진우')) cat = '생활';
    if (cat) resolved.push({ ...b, cat });
    else stillUnresolved[b.item] = (stillUnresolved[b.item] || 0) + 1;
  });

  const byCat = {};
  resolved.forEach(r => { byCat[r.cat] = byCat[r.cat] || []; byCat[r.cat].push(r.item); });
  console.log('=== 분류 제안 요약 (dry-run, 미기록) ===');
  Object.entries(byCat).forEach(([cat, items]) => {
    console.log(`${cat}: ${items.length}건`);
  });
  console.log('\n미해결(사전에 없음):', Object.keys(stillUnresolved).length, '개 항목,', Object.values(stillUnresolved).reduce((a,b)=>a+b,0), '건');
  Object.entries(stillUnresolved).forEach(([item, c]) => console.log(' ', c, item));

  require('fs').writeFileSync(
    '/private/tmp/claude-501/-Users-yunhye/925c9a4e-69d2-4453-878a-b4107830b637/scratchpad/resolved.json',
    JSON.stringify(resolved, null, 1)
  );
}
main().catch(e => console.error(e.message));
